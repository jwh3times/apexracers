DO $$
DECLARE
    v_week_id    INTEGER;
    car_ids      INTEGER[]          := ARRAY[9001,9002,9003,9004,9005,9006,9007,9008,9009,9010,9011];
    driver_base  INTEGER[]          := ARRAY[510000,520000,530000,540000,550000,560000,570000,580000,590000,600000,610000];
    p0           DOUBLE PRECISION[] := ARRAY[70.5,71.0,69.8,71.2,71.0,70.2,71.7,71.4,71.0,71.1,72.4];
    p25          DOUBLE PRECISION[] := ARRAY[71.4,71.9,70.7,72.1,71.9,71.1,72.6,72.3,71.8,71.9,73.3];
    p50          DOUBLE PRECISION[] := ARRAY[72.2,72.7,71.5,72.9,72.7,71.9,73.5,73.1,72.6,72.8,74.2];
    p75          DOUBLE PRECISION[] := ARRAY[73.3,73.8,72.6,74.0,73.8,73.0,74.7,74.2,73.7,73.9,75.4];
    p100         DOUBLE PRECISION[] := ARRAY[76.0,76.6,75.3,76.9,76.6,75.7,77.7,77.3,76.6,76.9,78.5];
    user_laps    DOUBLE PRECISION[] := ARRAY[72.0,72.5,71.3,72.7,72.5,71.7,73.2,72.9,72.4,72.6,73.9];
    c            INTEGER;
    i            INTEGER;
    r            DOUBLE PRECISION;
    lap_secs     DOUBLE PRECISION;
BEGIN
    SELECT "Id" INTO v_week_id FROM "Weeks"
    WHERE "SeasonId" = 9001 AND "WeekNumber" = 1;

    FOR c IN 1..11 LOOP
        -- 499 random drivers
        FOR i IN 1..499 LOOP
            r        := random();
            lap_secs := CASE
                WHEN r < 0.25 THEN p0[c]  + (r          / 0.25) * (p25[c]  - p0[c])
                WHEN r < 0.50 THEN p25[c] + ((r - 0.25) / 0.25) * (p50[c]  - p25[c])
                WHEN r < 0.75 THEN p50[c] + ((r - 0.50) / 0.25) * (p75[c]  - p50[c])
                ELSE               p75[c] + ((r - 0.75) / 0.25) * (p100[c] - p75[c])
            END;
            INSERT INTO "LapTimeEntries" (
                "DriverCustomerId","CarId","WeekId",
                "LapTimeSeconds","AirTempCelsius","TrackTempCelsius","TrackWetness","RecordedAt"
            ) VALUES (
                driver_base[c] + i, car_ids[c], v_week_id,
                ROUND(lap_secs::NUMERIC,4)::DOUBLE PRECISION,
                (18.0 + random()*8.0)::FLOAT, (28.0 + random()*15.0)::FLOAT, 0,
                '2026-03-17 00:00:00+00'::TIMESTAMPTZ + (random()*INTERVAL '7 days')
            );
        END LOOP;

        -- Customer 100100 — explicit lap for cars 1,2,4,8,11 only
        IF c = ANY(ARRAY[1,2,4,8,11]) THEN
            INSERT INTO "LapTimeEntries" (
                "DriverCustomerId","CarId","WeekId",
                "LapTimeSeconds","AirTempCelsius","TrackTempCelsius","TrackWetness","RecordedAt"
            ) VALUES (
                100100, car_ids[c], v_week_id,
                user_laps[c], 22.0, 35.0, 0,
                '2026-03-18 14:00:00+00'::TIMESTAMPTZ
            );
        END IF;

        RAISE NOTICE 'St. Petersburg Week 1: seeded laps for CarId=%.', car_ids[c];
    END LOOP;
END $$;

