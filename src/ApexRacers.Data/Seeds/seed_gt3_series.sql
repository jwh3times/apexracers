    car_ids      INTEGER[]          := ARRAY[9001,9002,9003,9004,9005,9006,9007,9008,9009,9010,9011];
    driver_base  INTEGER[]          := ARRAY[1170000,1180000,1190000,1200000,1210000,1220000,1230000,1240000,1250000,1260000,1270000];
    p0           DOUBLE PRECISION[] := ARRAY[112.5,102.0,104.0,107.0,105.0,110.5,104.5,106.0,103.0,108.0,109.0];
    p25          DOUBLE PRECISION[] := ARRAY[113.8,103.3,105.3,108.3,106.3,111.8,105.8,107.3,104.3,109.3,110.3];
    p50          DOUBLE PRECISION[] := ARRAY[115.0,104.5,106.5,109.5,107.5,113.0,107.0,108.5,105.5,110.5,111.5];
    p75          DOUBLE PRECISION[] := ARRAY[117.0,106.5,108.5,111.5,109.5,115.0,109.0,110.5,107.5,112.5,113.5];
    p100         DOUBLE PRECISION[] := ARRAY[125.0,114.5,116.5,119.5,117.5,123.0,117.0,118.5,115.5,120.5,121.5];
    c            INTEGER;
    i            INTEGER;
    r            DOUBLE PRECISION;
    lap_secs     DOUBLE PRECISION;
BEGIN
    SELECT "Id" INTO v_week_id FROM "Weeks"
    WHERE "SeasonId" = 9001 AND "WeekNumber" = 9;

    FOR c IN 1..11 LOOP
        FOR i IN 1..500 LOOP
            r        := random();
            lap_secs := CASE
                WHEN r < 0.25 THEN p0[c]  + (r          / 0.25) * (p25[c]  - p0[c])
                WHEN r < 0.50 THEN p25[c] + ((r - 0.25) / 0.25) * (p50[c]  - p25[c])
                WHEN r < 0.75 THEN p50[c] + ((r - 0.50) / 0.25) * (p75[c]  - p50[c])
                ELSE               p75[c] + ((r - 0.75) / 0.25) * (p100[c] - p75[c])
            END;
            INSERT INTO "LapTimeEntries" (
                "DriverCustomerId","CarId","WeekId",
                "LapTimeSeconds","AirTempCelsius","TrackTempCelsius","TrackWetness","RecordedAt"
            ) VALUES (
                driver_base[c] + i, car_ids[c], v_week_id,
                ROUND(lap_secs::NUMERIC,4)::DOUBLE PRECISION,
                (16.0 + random()*9.0)::FLOAT, (28.0 + random()*17.0)::FLOAT, 0,
                '2026-05-12 00:00:00+00'::TIMESTAMPTZ + (random()*INTERVAL '7 days')
            );
        END LOOP;

        RAISE NOTICE 'Mugello Week 9: seeded 500 laps for CarId=%.', car_ids[c];
    END LOOP;
END $$;

-- ── 12. Verification ──────────────────────────────────────────────────────────

SELECT
    w."WeekNumber"                                                             AS "Week",
    w."TrackName"                                                              AS "Track",
    c."Name"                                                                   AS "Car",
    COUNT(l."Id")                                                              AS "Entries",
    BOOL_OR(l."DriverCustomerId" = 100100)                                     AS "Has 100100",
    MIN(l."LapTimeSeconds")                                                    AS "Fastest (s)",
    PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY l."LapTimeSeconds")           AS "Median (s)"
FROM "Weeks" w
JOIN "Seasons" s         ON s."Id"     = w."SeasonId" AND s."Id" = 9001
JOIN "SeasonCars" sc     ON sc."SeasonId" = s."Id"
JOIN "Cars" c            ON c."Id"     = sc."CarId"
LEFT JOIN "LapTimeEntries" l ON l."CarId" = c."Id" AND l."WeekId" = w."Id"
GROUP BY w."WeekNumber", w."TrackName", c."Id", c."Name"
ORDER BY w."WeekNumber", c."Id";

COMMIT;
